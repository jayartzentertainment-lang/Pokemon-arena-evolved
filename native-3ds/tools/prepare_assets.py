#!/usr/bin/env python3
"""Convert user-owned Platinum/Arena inputs to cropped Citro2D atlas inputs.

No ROM or SDK is downloaded. Private source art and generated textures are
ignored by version control. Preserve per-direction anchors and original timing.
"""
import argparse
from collections import deque
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess
import tempfile

from PIL import Image,ImageDraw

ROOT=Path(__file__).resolve().parents[1]
ANIMS=['Idle','Walk','Shoot','Attack','Special']


def sha(data):return hashlib.sha256(data).hexdigest()


def palette(words):
    return [((w&31)*8,((w>>5)&31)*8,((w>>10)&31)*8,255 if i else 0)
            for i,w in enumerate(words)]


def decode_tiles(raw,width,height,colors):
    im=Image.new('RGBA',(width,height))
    pixels=[]
    for y in range(height):
        for x in range(width):
            off=((y//8)*(width//8)+x//8)*32+(y&7)*4+(x&7)//2
            pixels.append(colors[(raw[off]>>((x&1)*4))&15])
    im.putdata(pixels)
    return im


def opaque_sheet_key(im):
    """Flood-fill neutral sheet matte; enclosed white water cores survive."""
    im=im.copy();px=im.load();w,h=im.size
    queue=deque([(x,y) for x in range(w) for y in (0,h-1)]+
                [(x,y) for y in range(h) for x in (0,w-1)])
    seen=set()
    while queue:
        x,y=queue.popleft()
        if (x,y) in seen or not(0<=x<w and 0<=y<h):continue
        seen.add((x,y));r,g,b,a=px[x,y]
        if a and not(min(r,g,b)>=230 and max(r,g,b)-min(r,g,b)<=8):continue
        px[x,y]=(0,0,0,0)
        queue.extend(((x-1,y),(x+1,y),(x,y-1),(x,y+1)))
    return im


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--all-species',action='store_true',help='Convert all493 authentic directional sets from the supplied pack')
    parser.add_argument('--ds-source',type=Path,required=True)
    parser.add_argument('--extra-effects',type=Path,required=True)
    parser.add_argument('--dp-effects',type=Path,required=True)
    parser.add_argument('--emerald-source',type=Path,required=True,
                        help='Supplied Arena workspace with graphics/arena/flame/sheet.png')
    args=parser.parse_args()
    (ROOT/'validation').mkdir(parents=True,exist_ok=True)
    (ROOT/'romfs/gfx').mkdir(parents=True,exist_ok=True)
    original=ROOT/'vendor/platinum096'
    private=ROOT/'gfx/private';private.mkdir(parents=True,exist_ok=True)
    manifest={'scope':'493 base-species directional art and data; move-specific mechanics coverage remains separate' if args.all_species else 'Four-species native3DS combat slice',
              'format':'Citro2D atlas inputs, RGBA5551, nearest-neighbour',
              'species':[],'effects':[],'sources':{},'font':'Public-domain font8x8_basic; see provenance/font8x8-LICENSE.txt'}
    with tempfile.TemporaryDirectory(prefix='arena-metadata-') as temp:
        executable=Path(temp)/'metadata'
        subprocess.run(['cc','-std=c11','-I'+str(original/'include'),str(ROOT/'tools/export_metadata.c'),
                        str(original/'src/arena/assets_data.c'),'-o',str(executable)],check=True)
        mons=json.loads(subprocess.check_output([str(executable)]+(['all'] if args.all_species else []),text=True))
    pack=(args.ds_source/'res/arena/arena.pack').read_bytes()
    baseline=json.loads((ROOT/'provenance/ds-096-source-manifest.json').read_text())
    expected=baseline['files_sha256']['added-files/res/arena/arena.pack']
    if sha(pack)!=expected:raise ValueError('Sprite pack differs from preserved0.9.6 source')
    manifest['arena_pack_sha256']=sha(pack)
    type_ids={s:i for i,s in enumerate((args.ds_source/'generated/pokemon_types.txt').read_text().splitlines())}
    move_ids={s:i for i,s in enumerate((args.ds_source/'generated/moves.txt').read_text().splitlines())}
    moves={25:['THUNDERBOLT','QUICK_ATTACK','THUNDER_WAVE','DOUBLE_TEAM'],
           448:['AURA_SPHERE','FORCE_PALM','METAL_CLAW','SWORDS_DANCE'],
           6:['FLAMETHROWER','SLASH','SMOKE_SCREEN','DRAGON_CLAW'],
           9:['HYDRO_PUMP','WATER_PULSE','TACKLE','PROTECT']}
    scales={25:1.3,448:1.45,6:1.65,9:1.65,130:2.0,131:1.125};styles={25:0,448:1,6:2,9:3}
    header=['/* Generated by tools/prepare_assets.py. */','#include "assets3ds.h"']
    definitions=[]
    contact=Image.new('RGB',(8*112,4*124),(40,48,56));draw=ImageDraw.Draw(contact)
    for row,mon in enumerate(mons):
        dex=mon['dex'];name=mon['name'];out=private/f'pokemon_{dex:04d}';out.mkdir(exist_ok=True)
        unique={};raw_cache={};images=[];anim_defs=[];mon_record={'dex':dex,'name':name,'directional':True,'animations':[]}
        colors=palette(mon['palette'])
        for slot,anim in enumerate(mon['animations']):
            start=anim['offset'];blob=pack[start:start+anim['bytes']]
            dictionary,count=struct.unpack_from('<II',blob)
            assert dictionary+count*32<=len(blob)
            frames=[]
            for direction in range(8):
                for frame in range(anim['frames']):
                    ids=struct.unpack_from('<64H',blob,8+(direction*anim['frames']+frame)*128)
                    assert max(ids)<count
                    raw=b''.join(blob[dictionary+i*32:dictionary+(i+1)*32] for i in ids)
                    if raw not in raw_cache:
                        source_image=decode_tiles(raw,64,64,colors)
                        raw_cache[raw]=(source_image,source_image.getbbox())
                    im,bounds=raw_cache[raw]
                    if not bounds:raise ValueError(f'Empty source pose {dex}/{slot}/{direction}/{frame}')
                    crop=im.crop(bounds);key=(crop.size,sha(crop.tobytes()))
                    if key not in unique:
                        unique[key]=len(images);filename=f'f{len(images):04d}.png'
                        crop.save(out/filename);images.append(filename)
                    frames.append((unique[key],32-bounds[0],32+anim['ground'][direction]-bounds[1],*crop.size))
                    if row<4 and slot==2 and frame==min(anim['frames']-1,1):
                        # Shoot/attack contact views for manual emitter calibration.
                        shown=im.resize((96,96),Image.Resampling.NEAREST)
                        contact.paste(shown,(direction*112,row*124+24),shown)
                        draw.text((direction*112+2,row*124+2),name[:10]+' '+str(direction),fill='white')
            prefix=f'm{dex}_{slot}'
            header.append('static const uint8_t '+prefix+'_times[]={'+','.join(map(str,anim['durations']))+'};')
            header.append('static const ArenaSpriteFrame '+prefix+'_frames[]={'+
                          ','.join('{'+','.join(map(str,f))+'}' for f in frames)+'};')
            anim_defs.append('{%d,%d,%d,%s_times,%s_frames}'%(anim['frames'],anim['total_ticks'],anim['hit_tick'],prefix,prefix))
            mon_record['animations'].append({**anim,'name':ANIMS[slot],'frame_records':[list(f) for f in frames]})
        t3s='--atlas -f rgba5551 -z auto\n'+'\n'.join('private/'+out.name+'/'+f for f in images)+'\n'
        (ROOT/'gfx'/f'pokemon_{dex:04d}.t3s').write_text(t3s)
        data=json.loads((args.ds_source/'res/pokemon'/name.lower()/'data.json').read_text())
        stats=data['base_stats'];hp=(2*stats['hp']+31)//2+60
        stat=lambda key:(2*stats[key]+31)//2+5
        types=[type_ids[t] for t in data['types']]
        equipped=[move_ids['MOVE_'+m] for m in moves[dex]] if dex in moves else [move_ids[v] for lv,v in data['learnset']['by_level'] if lv<=50][-4:]
        equipped=([move_ids['MOVE_TACKLE']]*(4-len(equipped)))+equipped
        config='{%d,%d,%d,%d,%d,{%s},{%s},%d,%d}'%(dex,hp,stat('attack'),stat('defense'),stat('speed'),
                ','.join(map(str,equipped)),','.join(map(str,types)),stat('special_attack'),stat('special_defense'))
        definitions.append('{%d,"%s","romfs:/gfx/pokemon_%04d.t3x",%sf,%d,%s,{%s}}'%
                           (dex,name,dex,str(scales.get(dex,1.4 if dex not in (130,149,208,321,487) else 1.85)),styles.get(dex,0),config,','.join(anim_defs)))
        mon_record.update(unique_images=len(images),base_stats=stats,types=types,learned_moves=equipped)
        manifest['species'].append(mon_record)
    header.append('const ArenaSpecies gSpecies[]={'+',\n'.join(definitions)+'};')
    header.append('const unsigned gSpeciesCount=sizeof(gSpecies)/sizeof(gSpecies[0]);')
    header.append('const ArenaSpecies *ArenaSpecies_Find(unsigned dex){unsigned i;for(i=0;i<gSpeciesCount;i++)if(gSpecies[i].dex==dex)return &gSpecies[i];return 0;}')
    (ROOT/'source/game/species_data.c').write_text('\n'.join(header)+'\n')
    contact.save(ROOT/'validation/directional-contact.png')

    fxdir=private/'effects';fxdir.mkdir(exist_ok=True)
    fximages=[];fxdefs=[]
    def load(path,crop=None,matte=False,rotate=0,registration=False):
        # PMD families often share filenames such as 0.png. Keep every source
        # record rather than letting one family's hash overwrite another.
        raw=path.read_bytes();manifest['sources'][str(path)]={'sha256':sha(raw),'bytes':len(raw),'source_path':str(path)}
        im=Image.open(path).convert('RGBA')
        if crop:im=im.crop(crop)
        if registration:
            im.putdata([(0,0,0,0) if r>190 and b>190 and g<100 else (r,g,b,a) for r,g,b,a in im.getdata()])
        if matte:im=opaque_sheet_key(im)
        if rotate:im=im.rotate(rotate,Image.Resampling.NEAREST,expand=True)
        return im
    def sequence(name,items,cap=(160,96),ticks=3):
        w=max(i.width for i in items);h=max(i.height for i in items);aligned=[]
        for im in items:
            out=Image.new('RGBA',(w,h));out.alpha_composite(im,((w-im.width)//2,(h-im.height)//2));aligned.append(out)
        boxes=[im.getbbox() for im in aligned if im.getbbox()]
        bounds=(min(b[0] for b in boxes),min(b[1] for b in boxes),max(b[2] for b in boxes),max(b[3] for b in boxes))
        factor=min(cap[0]/(bounds[2]-bounds[0]),cap[1]/(bounds[3]-bounds[1]),1)
        size=(max(1,round((bounds[2]-bounds[0])*factor)),max(1,round((bounds[3]-bounds[1])*factor)))
        first=len(fximages)
        for im in aligned:
            im=im.crop(bounds).resize(size,Image.Resampling.NEAREST)
            filename=f'e{len(fximages):03d}.png';im.save(fxdir/filename);fximages.append(filename)
        fxdefs.append('    FX_'+name+'='+str(first)+',')
        manifest['effects'].append({'name':name,'first_image':first,'frames':len(items),'shared_bounds':bounds,'size':size,'ticks_per_cel':ticks})
    extra=args.extra_effects;dp=args.dp_effects
    for name,filename in [('BOLT','111.png'),('THIN_FLAME','106.png')]:
        sequence(name,[load(extra/'0'/filename,(4,40*i+4,132,40*i+36),registration=True) for i in range(4)],(128,32))
    flame=args.emerald_source/'graphics/arena/flame/sheet.png'
    sequence('FLAME',[load(flame,(i*64,0,(i+1)*64,64)) for i in range(8)],(64,64),ticks=4)
    sequence('HYDRO',[load(dp/'Hydro-Pump.png',(0,row*144,256,(row+1)*144),matte=True,rotate=-45) for row in (2,3,4,5)],(176,60))
    sequence('IMPACT',[load(extra/'1/Effects'/f'Effects_{i}.png') for i in (0,1,3,6)],(64,64))
    sequence('WIND',[load(extra/'1/Effects'/f'Effects_{i}.png') for i in (164,165)],(64,16))
    sequence('GUARD',[load(extra/'0/24.png',box,registration=True) for box in [(0,7,120,17),(0,33,120,55),(0,74,120,110),(0,124,120,172),(0,187,120,236)]],(96,64))
    for name,number in [('AURA',240),('EMBER',5)]:
        paths=sorted((extra/'2/move_VFX'/f'{number:04d}'/'000').glob('*.png'))
        sequence(name,[load(paths[round((i+1)*(len(paths)-1)/5)]) for i in range(4)],(64,64))
    sequence('SWORDS',[load(dp/'Swords-Dance.png',(i*21,0,i*21+21,53)) for i in range(4)],(21,53))
    sequence('PULSE',[load(dp/'Water-Pulse.png',box) for box in [(0,0,120,124),(125,0,260,124)]],(40,40))
    (ROOT/'gfx/effects.t3s').write_text('--atlas -f rgba5551 -z auto\n'+'\n'.join('private/effects/'+f for f in fximages)+'\n')
    (ROOT/'include/generated/effects.h').write_text('/* Generated source image IDs. */\n#ifndef ARENA_FX_IDS\n#define ARENA_FX_IDS\nenum {\n'+'\n'.join(fxdefs)+'\n    FX_IMAGE_COUNT='+str(len(fximages))+'\n};\n#endif\n')

    # Original arena floor, with the same +32 world border used by navigation.
    raw=(args.ds_source/'res/arena/arena_bg0.bin').read_bytes();tilebytes=struct.unpack_from('<I',raw)[0]
    colors=[(*color[:3],255) for color in palette(struct.unpack_from('<16H',raw,4))]
    maps=struct.unpack_from('<2048H',raw,36)
    floor=Image.new('RGBA',(512,256))
    for y in range(32):
        for x in range(64):
            # DS 512px text BGs store adjacent 32x32 screen blocks, not
            # ordinary 64-wide scanlines. Keep the source floor contiguous.
            entry=maps[(x//32)*1024+y*32+x%32];index=entry&1023
            tile=decode_tiles(raw[4132+index*32:4132+(index+1)*32],8,8,colors)
            if entry&1024:tile=tile.transpose(Image.Transpose.FLIP_LEFT_RIGHT)
            if entry&2048:tile=tile.transpose(Image.Transpose.FLIP_TOP_BOTTOM)
            floor.paste(tile,(x*8,y*8))
    arena=Image.new('RGBA',(448,320))
    for y in range(320):
        for x in range(448):
            sx=x-32;sy=y-32
            if sx<0:sx=-sx-1
            elif sx>=384:sx=767-sx
            if sy<0:sy=-sy-1
            elif sy>=256:sy=511-sy
            arena.putpixel((x,y),floor.getpixel((sx,sy)))
    arena.save(private/'arena.png')
    (ROOT/'gfx/arena.t3s').write_text('--atlas -f rgba5551 -z auto\nprivate/arena.png\n')

    # Retain the supplied terrain and Pokeballs, never generic projectile orbs.
    source=(args.ds_source/'src/arena/effects_data.c').read_text()
    def c_values(name):
        match=re.search(r'\b'+name+r'\s*(?:\[[^\]]*\])+\s*=\s*\{',source)
        if not match:raise ValueError(name)
        start=match.end();end=start;depth=1
        while depth:
            if source[end]=='{':depth+=1
            elif source[end]=='}':depth-=1
            end+=1
        body=re.sub(r'/\*.*?\*/|//[^\n]*','',source[start:end-1],flags=re.S)
        return [int(x,0) for x in re.findall(r'0x[0-9a-fA-F]+|\b[0-9]+\b',body)]
    prop_tiles=c_values('arena_effect_tiles');prop_palettes=c_values('arena_effect_palettes')
    props=private/'props';props.mkdir(exist_ok=True);propfiles=[]
    for number in list(range(15))+[32,33,34]:
        filename=f'p{number:02d}.png'
        im=decode_tiles(bytes(prop_tiles[number*512:(number+1)*512]),32,32,
                        palette(prop_palettes[number*16:(number+1)*16]))
        if number>=32:im=im.crop(im.getbbox())
        im.save(props/filename);propfiles.append('private/props/'+filename)
    (ROOT/'gfx/props.t3s').write_text('--atlas -f rgba5551 -z auto\n'+'\n'.join(propfiles)+'\n')

    ui=Image.open(args.ds_source/'res/arena/battle-ui-preview.png').convert('RGBA')
    ui_dir=private/'ui';ui_dir.mkdir(exist_ok=True)
    def panel(width,height):
        src=ui.crop((6,80,124,114));w,h=src.size;border=6
        target=Image.new('RGBA',(width,height))
        for sy0,sy1,dy0,dy1 in [(0,border,0,border),(border,h-border,border,height-border),(h-border,h,height-border,height)]:
            for sx0,sx1,dx0,dx1 in [(0,border,0,border),(border,w-border,border,width-border),(w-border,w,width-border,width)]:
                target.paste(src.crop((sx0,sy0,sx1,sy1)).resize((dx1-dx0,dy1-dy0),Image.Resampling.NEAREST),(dx0,dy0))
        return target
    panel(164,28).save(ui_dir/'move.png');panel(96,34).save(ui_dir/'footer.png')
    (ROOT/'gfx/ui.t3s').write_text('--atlas -f rgba5551 -z auto\nprivate/ui/move.png\nprivate/ui/footer.png\n')

    font_source=(ROOT/'provenance/font8x8_basic.h').read_text()
    body=font_source.split('char font8x8_basic',1)[1].split('=',1)[1]
    body=re.sub(r'/\*.*?\*/|//[^\n]*','',body,flags=re.S)
    values=[int(s,16) for s in re.findall(r'0x([0-9A-Fa-f]{2})',body)]
    assert len(values)==128*8
    fontdir=private/'font';fontdir.mkdir(exist_ok=True)
    for ch in range(32,128):
        im=Image.new('RGBA',(8,8))
        for y in range(8):
            for x in range(8):
                if values[ch*8+y]&(1<<x):im.putpixel((x,y),(255,255,255,255))
        im.save(fontdir/f'c{ch:03d}.png')
    (ROOT/'gfx/font.t3s').write_text('--atlas -f rgba5551 -z auto\n'+'\n'.join(f'private/font/c{c:03d}.png' for c in range(32,128))+'\n')
    (ROOT/'assets/manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps({'species':len(mons),'unique_images':[m['unique_images'] for m in manifest['species']],
                      'effect_images':len(fximages),'original_durations_preserved':True,'private_art_not_for_public_source':True}))


if __name__=='__main__':main()
